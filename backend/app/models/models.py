"""
SQLAlchemy ORM models for TradePilot AI
"""
from datetime import datetime, timezone
from sqlalchemy import (
    Column, Integer, String, Float, Boolean, DateTime, JSON, Text, ForeignKey, Index
)
from sqlalchemy.orm import relationship
from backend.app.core.database import Base


def utc_now():
    return datetime.now(timezone.utc)


class AccountSnapshot(Base):
    """Periodic snapshots of demo account balance and equity"""
    __tablename__ = "account_snapshots"

    id = Column(Integer, primary_key=True, index=True)
    timestamp = Column(DateTime, default=utc_now, index=True, nullable=False)
    account_id = Column(String(64), nullable=True)
    balance = Column(Float, nullable=False)
    equity = Column(Float, nullable=False)
    margin = Column(Float, default=0.0)
    free_margin = Column(Float, default=0.0)
    margin_level = Column(Float, default=0.0)
    currency = Column(String(10), default="USD")
    is_demo = Column(Boolean, default=True, nullable=False)
    open_positions_count = Column(Integer, default=0)
    daily_pnl = Column(Float, default=0.0)
    weekly_pnl = Column(Float, default=0.0)


class MarketSnapshot(Base):
    """Snapshots of market candle data and indicator values"""
    __tablename__ = "market_snapshots"

    id = Column(Integer, primary_key=True, index=True)
    timestamp = Column(DateTime, default=utc_now, index=True, nullable=False)
    symbol = Column(String(20), index=True, nullable=False)
    timeframe = Column(String(10), default="M15", nullable=False)
    open = Column(Float, nullable=False)
    high = Column(Float, nullable=False)
    low = Column(Float, nullable=False)
    close = Column(Float, nullable=False)
    volume = Column(Float, default=0.0)
    spread = Column(Float, default=0.0)
    atr = Column(Float, nullable=True)
    rsi = Column(Float, nullable=True)
    ema_fast = Column(Float, nullable=True)
    ema_slow = Column(Float, nullable=True)
    regime = Column(String(32), default="uncertain")


class SignalRecord(Base):
    """Traceable trading signals generated by the strategy engine"""
    __tablename__ = "signals"

    id = Column(String(64), primary_key=True, index=True)  # UUID or deterministic hash
    timestamp = Column(DateTime, default=utc_now, index=True, nullable=False)
    symbol = Column(String(20), nullable=False)
    timeframe = Column(String(10), default="M15")
    strategy_name = Column(String(64), nullable=False)
    signal_type = Column(String(10), nullable=False)  # BUY, SELL, WAIT
    entry_price = Column(Float, nullable=False)
    stop_loss = Column(Float, nullable=False)
    take_profit = Column(Float, nullable=False)
    risk_reward_ratio = Column(Float, default=1.5)
    strategy_version = Column(String(32), default="v1.0")
    is_executed = Column(Boolean, default=False)
    rejection_reason = Column(String(255), nullable=True)

    ai_analysis = relationship("AiAnalysisRecord", back_populates="signal", uselist=False)
    risk_check = relationship("RiskCheckRecord", back_populates="signal", uselist=False)
    order = relationship("OrderRecord", back_populates="signal", uselist=False)


class AiAnalysisRecord(Base):
    """Schema-validated AI / ML market analysis and regime classification"""
    __tablename__ = "ai_analyses"

    id = Column(Integer, primary_key=True, index=True)
    timestamp = Column(DateTime, default=utc_now, index=True, nullable=False)
    signal_id = Column(String(64), ForeignKey("signals.id"), nullable=True)
    symbol = Column(String(20), nullable=False)
    decision = Column(String(10), nullable=False)  # BUY, SELL, WAIT
    market_regime = Column(String(32), nullable=False)  # trending, ranging, high_volatility, uncertain
    strategy = Column(String(64), nullable=True)
    confidence = Column(Float, nullable=True)
    trade_expectancy = Column(Float, nullable=True)
    supporting_evidence = Column(JSON, default=list)
    contradicting_evidence = Column(JSON, default=list)
    invalidation_conditions = Column(JSON, default=list)
    reasoning_summary = Column(Text, nullable=False)
    feature_timestamp = Column(DateTime, nullable=True)
    model_version = Column(String(64), default="tradepilot-deterministic-v1")

    signal = relationship("SignalRecord", back_populates="ai_analysis")


class RiskCheckRecord(Base):
    """Traceable risk check records evaluated by the deterministic risk service"""
    __tablename__ = "risk_checks"

    id = Column(Integer, primary_key=True, index=True)
    timestamp = Column(DateTime, default=utc_now, index=True, nullable=False)
    signal_id = Column(String(64), ForeignKey("signals.id"), nullable=True)
    symbol = Column(String(20), nullable=False)
    requested_volume = Column(Float, nullable=False)
    approved_volume = Column(Float, nullable=False)
    stop_loss_distance_pips = Column(Float, nullable=False)
    risk_amount = Column(Float, nullable=False)
    risk_pct = Column(Float, nullable=False)
    current_equity = Column(Float, nullable=False)
    current_open_risk_pct = Column(Float, default=0.0)
    daily_loss_pct = Column(Float, default=0.0)
    weekly_loss_pct = Column(Float, default=0.0)
    consecutive_losses = Column(Integer, default=0)
    trades_today = Column(Integer, default=0)
    is_approved = Column(Boolean, default=False, nullable=False)
    rejection_reason = Column(String(255), nullable=True)
    risk_engine_version = Column(String(32), default="v1.0")

    signal = relationship("SignalRecord", back_populates="risk_check")


class OrderRecord(Base):
    """Broker orders submitted through the centralized execution gateway"""
    __tablename__ = "orders"

    id = Column(Integer, primary_key=True, index=True)
    client_order_id = Column(String(64), unique=True, index=True, nullable=False)
    broker_order_id = Column(Integer, nullable=True, index=True)
    timestamp = Column(DateTime, default=utc_now, index=True, nullable=False)
    signal_id = Column(String(64), ForeignKey("signals.id"), nullable=True)
    symbol = Column(String(20), nullable=False)
    order_type = Column(String(10), nullable=False)  # BUY, SELL
    volume = Column(Float, nullable=False)
    requested_price = Column(Float, nullable=False)
    executed_price = Column(Float, nullable=True)
    sl = Column(Float, nullable=False)
    tp = Column(Float, nullable=False)
    status = Column(String(20), default="PENDING", nullable=False)  # PENDING, FILLED, REJECTED, CANCELLED
    retcode = Column(Integer, nullable=True)
    broker_comment = Column(String(255), nullable=True)
    magic_number = Column(Integer, default=1001)

    signal = relationship("SignalRecord", back_populates="order")


class PositionRecord(Base):
    """Active positions synced from broker and local tracking"""
    __tablename__ = "positions"

    id = Column(Integer, primary_key=True, index=True)
    ticket = Column(Integer, unique=True, index=True, nullable=False)
    symbol = Column(String(20), nullable=False)
    position_type = Column(String(10), nullable=False)  # BUY, SELL
    volume = Column(Float, nullable=False)
    open_price = Column(Float, nullable=False)
    current_price = Column(Float, nullable=False)
    sl = Column(Float, nullable=False)
    tp = Column(Float, nullable=False)
    swap = Column(Float, default=0.0)
    commission = Column(Float, default=0.0)
    profit = Column(Float, default=0.0)
    open_time = Column(DateTime, default=utc_now, nullable=False)
    status = Column(String(20), default="OPEN")  # OPEN, CLOSED
    strategy_used = Column(String(64), nullable=True)
    signal_id = Column(String(64), nullable=True)


class TradeRecord(Base):
    """Completed/closed trades with full performance, cost and exit details"""
    __tablename__ = "trades"

    id = Column(Integer, primary_key=True, index=True)
    ticket = Column(Integer, index=True, nullable=False)
    symbol = Column(String(20), nullable=False)
    trade_type = Column(String(10), nullable=False)  # BUY, SELL
    volume = Column(Float, nullable=False)
    open_price = Column(Float, nullable=False)
    close_price = Column(Float, nullable=False)
    sl = Column(Float, nullable=False)
    tp = Column(Float, nullable=False)
    open_time = Column(DateTime, nullable=False)
    close_time = Column(DateTime, nullable=False, index=True)
    gross_pnl = Column(Float, nullable=False)
    net_pnl = Column(Float, nullable=False)
    commission = Column(Float, default=0.0)
    swap = Column(Float, default=0.0)
    slippage = Column(Float, default=0.0)
    exit_reason = Column(String(64), default="TP_OR_SL")  # TAKE_PROFIT, STOP_LOSS, MANUAL, EMERGENCY_FLATTEN
    strategy_used = Column(String(64), default="trend_following")
    model_version = Column(String(64), default="tradepilot-deterministic-v1")
    market_regime = Column(String(32), default="trending")
    signal_id = Column(String(64), nullable=True)


class AuditEvent(Base):
    """System events, state transitions, risk alerts, and errors"""
    __tablename__ = "audit_events"

    id = Column(Integer, primary_key=True, index=True)
    timestamp = Column(DateTime, default=utc_now, index=True, nullable=False)
    event_type = Column(String(64), index=True, nullable=False)
    severity = Column(String(16), default="INFO", nullable=False)  # INFO, WARNING, ERROR, CRITICAL
    message = Column(Text, nullable=False)
    metadata_json = Column(JSON, default=dict)


class BotStateRecord(Base):
    """Persistent audit log of bot state changes"""
    __tablename__ = "bot_state_records"

    id = Column(Integer, primary_key=True, index=True)
    timestamp = Column(DateTime, default=utc_now, index=True, nullable=False)
    current_state = Column(String(32), nullable=False)
    previous_state = Column(String(32), nullable=True)
    reason = Column(String(255), nullable=False)
    error_message = Column(Text, nullable=True)


class PerformanceSummary(Base):
    """Periodic performance metrics summary"""
    __tablename__ = "performance_summaries"

    id = Column(Integer, primary_key=True, index=True)
    period_type = Column(String(16), nullable=False)  # DAILY, WEEKLY, MONTHLY
    period_start = Column(DateTime, nullable=False)
    period_end = Column(DateTime, nullable=False)
    starting_balance = Column(Float, nullable=False)
    ending_balance = Column(Float, nullable=False)
    starting_equity = Column(Float, nullable=False)
    ending_equity = Column(Float, nullable=False)
    realized_pnl = Column(Float, nullable=False)
    unrealized_pnl = Column(Float, default=0.0)
    total_trades = Column(Integer, default=0)
    winning_trades = Column(Integer, default=0)
    losing_trades = Column(Integer, default=0)
    win_rate = Column(Float, default=0.0)
    profit_factor = Column(Float, default=0.0)
    max_drawdown_pct = Column(Float, default=0.0)
    avg_win = Column(Float, default=0.0)
    avg_loss = Column(Float, default=0.0)
    expectancy = Column(Float, default=0.0)
    metrics_json = Column(JSON, default=dict)


class GeneratedReport(Base):
    """Audit record of exported PDF and CSV reports"""
    __tablename__ = "generated_reports"

    id = Column(Integer, primary_key=True, index=True)
    timestamp = Column(DateTime, default=utc_now, index=True, nullable=False)
    period_type = Column(String(16), nullable=False)  # DAILY, WEEKLY, MONTHLY
    file_path = Column(String(255), nullable=False)
    file_format = Column(String(10), nullable=False)  # PDF, CSV, JSON
    filename = Column(String(128), nullable=False)
    summary_metrics_json = Column(JSON, default=dict)
